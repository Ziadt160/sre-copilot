// Generates src/contracts/agent.types.ts from agent.schema.json (itself exported from the Python
// contracts). `--check` regenerates in memory and fails when the committed file differs, so CI
// catches a schema change whose types were not regenerated.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const schemaPath = fileURLToPath(new URL("../src/contracts/agent.schema.json", import.meta.url));
const outPath = fileURLToPath(new URL("../src/contracts/agent.types.ts", import.meta.url));

const banner = `// GENERATED by scripts/gen-types.mjs from agent.schema.json. Do not edit: run \`npm run gen:types\`.
`;

async function render() {
  const schemas = JSON.parse(await readFile(schemaPath, "utf8"));
  // One compile over everything: separate compiles would each emit their own `ThreadId`,
  // `Turn`, ... and collide. Only AgentEvent carries $defs; hoist them to the root.
  const defs = { ...schemas.AgentEvent.$defs };
  for (const name of Object.keys(schemas).sort()) {
    const schema = { ...schemas[name] };
    delete schema.$defs;
    defs[name] = schema;
  }
  // The server dumps events with their defaults filled in, so every event property is always
  // present: mark them required (pydantic leaves defaulted fields out of `required`).
  for (const def of Object.values(schemas.AgentEvent.$defs)) {
    if (def.properties && def.type === "object") def.required = Object.keys(def.properties);
  }
  const root = {
    title: "AgentContracts",
    type: "object",
    properties: Object.fromEntries(Object.keys(schemas).map((n) => [n, { $ref: `#/$defs/${n}` }])),
    required: Object.keys(schemas),
    $defs: defs,
  };
  const ts = await compile(root, "AgentContracts", {
    bannerComment: "",
    additionalProperties: false,
    format: false,
    unreachableDefinitions: true,
  });
  return (banner + "\n" + ts).replace(/\r\n/g, "\n");
}

const next = await render();
if (process.argv.includes("--check")) {
  let current = "";
  try {
    current = (await readFile(outPath, "utf8")).replace(/\r\n/g, "\n");
  } catch {
    // missing file counts as drift
  }
  if (current !== next) {
    console.error("agent.types.ts is stale: run `npm run gen:types` and commit the result.");
    process.exit(1);
  }
  console.log("agent.types.ts is current");
} else {
  await writeFile(outPath, next, "utf8");
  console.log(`wrote ${outPath}`);
}
